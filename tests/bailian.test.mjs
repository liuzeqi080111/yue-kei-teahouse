import assert from 'node:assert/strict';
import {createBailian} from '../server/bailian.mjs';
const env={DASHSCOPE_API_KEY:'test-secret',BAILIAN_OPENAI_BASE_URL:'https://workspace.cn-beijing.maas.aliyuncs.com/compatible-mode/v1'};
const json=x=>new Response(JSON.stringify(x),{headers:{'Content-Type':'application/json'}});
let calls=[];
let response=()=>json({choices:[{message:{content:'唔該，加水。'}}]});
const api=createBailian({env,fetchImpl:async(u,o)=>{calls.push({u:String(u),o});return response(u,o);}});
assert.ok(!JSON.stringify(api.status()).includes('test-secret'));
await assert.rejects(createBailian({env:{}}).speak({text:'你好'}),{code:'PROVIDER_UNCONFIGURED'});
await assert.rejects(api.transcribe({audioBase64:'!!!',mimeType:'audio/wav'}),{code:'INVALID_INPUT'});
await assert.rejects(api.transcribe({audioBase64:'YQ==',mimeType:'text/html'}),{code:'INVALID_INPUT'});
assert.equal(calls.length,0);
assert.equal((await api.transcribe({audioBase64:'YQ==',mimeType:'audio/wav'})).text,'唔該，加水。');
let body=JSON.parse(calls.at(-1).o.body);assert.equal(body.asr_options.language,'yue');assert.equal(body.model,'qwen3-asr-flash');
response=()=>json({choices:[{message:{content:JSON.stringify({decision:'execute',intents:[{type:'REQUEST_WATER'}],reply:''})}}]});
assert.equal((await api.interpret({text:'加水',context:{allowedActions:['REQUEST_WATER']}})).intents[0].type,'REQUEST_WATER');
body=JSON.parse(calls.at(-1).o.body);assert.equal(body.enable_thinking,false);assert.ok(!body.messages[0].content.includes('REQUEST_ORDER_REVIEW'));
response=()=>json({choices:[{message:{content:'not json'}}]});
await assert.rejects(api.interpret({text:'加水',context:{}}),{code:'INVALID_MODEL_JSON'});
response=()=>new Response('{"detail":"private upstream secret"}',{status:401});
await assert.rejects(api.interpret({text:'你好',context:{}}),e=>e.code==='UPSTREAM_STATUS'&&!e.message.includes('private'));
response=(url)=>String(url).includes('/generation')?json({output:{audio:{url:'http://audio.aliyuncs.com/a.wav'}}}):new Response(Buffer.from([1,2,3]),{headers:{'Content-Type':'audio/wav'}});
assert.equal((await api.speak({text:'你好'})).audioBase64,'AQID');
assert.equal(calls.at(-1).u,'https://audio.aliyuncs.com/a.wav');assert.equal(calls.at(-1).o.headers,undefined);
response=(url)=>String(url).includes('/generation')?json({output:{audio:{url:'https://audio.aliyuncs.com/a.wav'}}}):new Response(null,{status:302,headers:{location:'https://evil.example/a.wav'}});
await assert.rejects(api.speak({text:'你好'}),{code:'UNTRUSTED_AUDIO_URL'});
response=(url)=>String(url).includes('/generation')?json({output:{audio:{url:'https://audio.aliyuncs.com/a.wav'}}}):new Response(new Uint8Array(2*1024*1024+1),{headers:{'Content-Type':'audio/wav'}});
await assert.rejects(api.speak({text:'你好'}),{code:'AUDIO_TOO_LARGE'});
console.log('PASS Bailian provider: ASR/NPC/TTS protocol, invalid input, safe errors, bounded download and redirects');
