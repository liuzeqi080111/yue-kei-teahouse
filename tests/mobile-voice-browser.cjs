const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const assert=require('node:assert/strict');
(async()=>{
 const {createServer}=await import('../server.mjs');let statusCalls=0,interpretCalls=0,transcribeCalls=0;
 const server=createServer({provider:{status:()=>{statusCalls++;if(statusCalls===1)throw Error('offline');return {configured:true,asr:true,npc:true,tts:true};},transcribe:async()=>{transcribeCalls++;return {text:'一杯咖啡'};},interpret:async()=>{interpretCalls++;return {decision:'reply',intents:[],reply:'你好',meaning:'你好'};},speak:async()=>{throw Error('audio test');}}});
 await new Promise(r=>server.listen(0,'127.0.0.1',r));
 const browser=await chromium.launch({channel:'msedge',headless:true,args:['--use-fake-ui-for-media-stream','--use-fake-device-for-media-stream']});
 try{
 const page=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true,permissions:['microphone']});
 await page.addInitScript(()=>{
  AbortSignal.timeout=undefined;
  const viewport=window.visualViewport;
  window.testKeyboard=height=>{
   if(height===null)delete viewport.height;else Object.defineProperty(viewport,'height',{value:height,configurable:true});
   viewport.dispatchEvent(new Event('resize'));
  };
 });
 await page.goto(`http://127.0.0.1:${server.address().port}/`);
 await page.locator('#welcome [data-dialog="chapters"]').click();await page.locator('[data-chapter="order"]').click();await page.locator('#learning-mode [data-learning-mode="beginner"]').click();
 assert.equal(await page.locator('#voice-dock').getAttribute('open'),null);
 const speak=page.locator('[data-tray-panel="voice"]'),learn=page.locator('[data-tray-panel="learn"]');
 assert.equal(await page.locator('.mobile-tray-goal').isVisible(),true);
 await learn.tap();assert.equal(await learn.getAttribute('aria-expanded'),'true');
 assert.equal(await page.locator('#voice-dock').isVisible(),false);
 await speak.tap();assert.equal(await learn.getAttribute('aria-expanded'),'false');
 assert.equal(await page.locator('#learning-guide').isVisible(),false);
 assert.equal(await speak.getAttribute('aria-expanded'),'true');
 assert.equal(await page.locator('#voice-dock').isVisible(),true);
 await page.getByRole('button',{name:'重新連接語音',exact:true}).waitFor();
 const input=page.locator('#voice-host textarea');await input.tap();await input.fill('一杯咖啡');
 const send=page.getByRole('button',{name:'發送文字',exact:true});
 assert.equal(await send.isEnabled(),true);
 await page.evaluate(()=>testKeyboard(445));
 const inset=await page.evaluate(()=>parseFloat(document.body.style.getPropertyValue('--mobile-bottom-inset')));
 assert.ok(inset>350);
 await send.scrollIntoViewIfNeeded();
 const sendBox=await send.boundingBox();
 assert.ok(sendBox.y>=0&&sendBox.y+sendBox.height<=446,'send button remains above a simulated mobile keyboard');
 await page.evaluate(()=>testKeyboard(null));
 assert.equal(await page.getByRole('button',{name:'开始说话',exact:true}).isEnabled(),true);
 const prevented=await input.evaluate(el=>{const e=new KeyboardEvent('keydown',{key:'Enter',isComposing:true,bubbles:true,cancelable:true});el.dispatchEvent(e);return e.defaultPrevented;});assert.equal(prevented,false);assert.equal(interpretCalls,0);
 assert.equal(await page.locator('#meaning').evaluate(el=>el.hidden),false);assert.equal(await page.locator('#translation').getAttribute('aria-pressed'),'true');
 await page.getByRole('button',{name:'發送文字',exact:true}).tap();await page.waitForFunction(()=>document.querySelector('.voice-reply').textContent==='你好');assert.equal(interpretCalls,1);assert.equal(await page.locator('#meaning').isVisible(),true);assert.equal(await input.inputValue(),'一杯咖啡');
 await page.locator('.mobile-tray-panels').evaluate(el=>el.scrollTop=el.scrollHeight);const status=await page.locator('.voice-status').boundingBox(),host=await page.locator('.mobile-tray-panels').boundingBox();assert.ok(status.y>=host.y-1&&status.y<host.y+host.height);
 const mic=page.getByRole('button',{name:'开始说话',exact:true});
 await mic.tap();
 await page.getByRole('button',{name:'停止录音',exact:true}).waitFor();
 await page.getByRole('button',{name:'取消本次語音',exact:true}).tap();
 await page.locator('.voice-status').filter({hasText:'已取消'}).waitFor();
 assert.equal(transcribeCalls,0);
 await mic.tap();
 const stop=page.getByRole('button',{name:'停止录音',exact:true});
 await stop.waitFor();await page.waitForTimeout(700);
 await Promise.all([page.waitForResponse(response=>response.url().endsWith('/api/voice/interpret')&&response.ok()),stop.tap()]);
 assert.equal(transcribeCalls,1);
 assert.equal(interpretCalls,2);
 assert.equal(await page.locator('.voice-transcript').isVisible(),false);
 await page.getByLabel('显示识别文字').check();
 assert.equal(await page.locator('.voice-transcript').innerText(),'一杯咖啡');
 await page.keyboard.press('Escape');
 assert.equal(await speak.getAttribute('aria-expanded'),'false');
 assert.equal(await speak.evaluate(el=>el===document.activeElement),true);
 await page.setViewportSize({width:844,height:390});
 assert.equal(await speak.isVisible(),true);
 await speak.tap();
 assert.equal(await page.locator('#voice-dock').isVisible(),true);
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await page.screenshot({path:'output/voice-qa/mobile-recovery.png'});
 console.log('PASS mobile: legacy AbortSignal, failed status does not lock text/record, IME Enter, touch send and cancel, simulated keyboard, one pane at a time, landscape and translated subtitles');
 }finally{await browser.close();server.closeAllConnections();await new Promise(r=>server.close(r));}
})().catch(e=>{console.error(e);process.exitCode=1;});
