import assert from 'node:assert/strict';
import {createGame} from '../controller.js';
import {createVoiceBridge} from '../voice-bridge.js';

let scheduled=[];
const game=createGame({schedule:fn=>{scheduled.push(fn);return fn},cancel:fn=>{scheduled=scheduled.filter(item=>item!==fn)}});
const flush=()=>{let limit=100;while(scheduled.length&&limit-->0)scheduled.shift()();assert.ok(limit>0)};
const bridge=createVoiceBridge({game});
game.action('ENTER');flush();
assert.equal(bridge.apply({decision:'execute',intents:[{type:'START_SEATING',partySize:2}],playerText:'两位'},bridge.token()).ok,true);flush();
assert.equal(game.snapshot().state.waiterPresent,false);
const tokenBeforeCallingWaiter=bridge.token();
const reply=bridge.apply({decision:'clarify',intents:[],reply:'絲襪奶茶要凍定熱？',meaning:'丝袜奶茶要冰的还是热的？',question:'絲襪奶茶要凍定熱？',playerText:'我要一杯丝袜奶茶'},bridge.token());
assert.equal(reply.ok,true);
game.say(reply.reply,reply.meaning);flush();
assert.equal(game.snapshot().state.waiterPresent,true);
assert.equal(bridge.apply({decision:'execute',intents:[{type:'ADD_ITEM',itemId:'drink-milk-tea',options:{temperature:'凍',sweetness:'少甜'}}]},tokenBeforeCallingWaiter).ok,false,'old execution token must still be rejected');
assert.ok(bridge.context().pendingQuestion,'NPC calling the waiter to ask the question must not erase that question');
assert.ok(bridge.context().history.some(row=>row.text.includes('我要一杯丝袜奶茶')),'retain the drink named in the current clarification');

const add=bridge.apply({decision:'execute',intents:[{type:'ADD_ITEM',itemId:'drink-milk-tea',options:{temperature:'凍',sweetness:'少甜'}}],playerText:'冻的，少甜'},bridge.token());
assert.equal(add.ok,true);
assert.equal(bridge.context().pendingQuestion,null,'resolved clarification must not remain pending');
assert.ok(bridge.context().history.some(row=>row.text.includes('我要一杯丝袜奶茶')),'ordinary order change retains recent dialogue under the confirmed architecture');
assert.ok(bridge.context().history.some(row=>row.text.includes('冻的，少甜')),'the preference is retained after adding the item');
game.action('REQUEST_WATER');flush();
assert.ok(bridge.context().history.some(row=>row.text.includes('冻的，少甜')),'service changes do not erase the preference');
assert.ok(bridge.context().history.length<=6,'context remains bounded');
game.action('RESTART');flush();
assert.equal(bridge.context().pendingQuestion,null,'new round clears clarification');
assert.deepEqual(bridge.context().history,[],'new round clears history');
game.chapter('bill');
for(let i=0;i<5;i++)bridge.apply({decision:'reply',reply:'请核对账单。',playerText:'第'+i+'次询问'},bridge.token());
assert.equal(bridge.context().history.length,6,'only the three latest exchanges are sent');
assert.equal(bridge.context().history.some(row=>row.text==='第0次询问'),false);
assert.equal(bridge.apply({decision:'execute',intents:[{type:'PAY_BILL'}],playerText:'确认付款'},bridge.token()).ok,true);flush();
assert.deepEqual(bridge.context().history,[],'finished meal clears dialogue without waiting for restart');
assert.equal(bridge.context().pendingQuestion,null);
console.log('PASS clarification survives waiter presentation while stale execution remains rejected and restart clears memory.');
