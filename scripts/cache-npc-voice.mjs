import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {createBailian} from '../server/bailian.mjs';
import {LINES} from '../controller.js';

// Run explicitly with the existing backend environment. Never print credentials.
const root=new URL('../',import.meta.url),provider=createBailian();
if(!provider.status().configured)throw Error('Voice provider is not configured');
const controller=await readFile(new URL('controller.js',root),'utf8');
const texts=new Set(Object.values(LINES).filter(line=>line[0].startsWith('阿明')).map(line=>line[1]));
for(const match of controller.matchAll(/\['阿明 · 侍應','([^']+)'/g))texts.add(match[1]);
for(const text of ['水加好喇，仲有咩需要？','餐具放好喇，仲有咩需要？','外賣包好喇，仲有咩需要？','餐點上齊喇，仲有咩需要？','小心熱，唔急，等涼少少先飲吖。'])texts.add(text);
for(const suffix of ['', '外賣記得拎埋。','堂食有剩都唔緊要。','外賣記得拎埋；堂食有剩都唔緊要。'])texts.add(`收妥喇，多謝晒！${suffix}慢行呀。`);
await mkdir(new URL('assets/',root),{recursive:true});
const entries=[];
for(const text of texts){
 const hash=createHash('sha256').update('qwen3-tts-flash:Rocky:'+text).digest('hex').slice(0,16);
 const file=`assets/npc-${hash}.wav`,dest=new URL(file,root);let bytes;
 try{bytes=await readFile(dest);}catch{}
 const wav=b=>b?.length>44&&b.toString('ascii',0,4)==='RIFF'&&b.toString('ascii',8,12)==='WAVE';
 if(!wav(bytes)){
  for(let attempt=0;attempt<2;attempt++){
   try{const data=await provider.speak({text});bytes=Buffer.from(data.audioBase64,'base64');if(!wav(bytes))throw Error('Expected WAV audio');await writeFile(dest,bytes);break;}
   catch(e){if(attempt===1)throw Error(`Clip ${entries.length+1} failed: ${e.code||e.name}`);}
  }
 }
 entries.push([text,file]);console.log(`Saved ${entries.length}/${texts.size}: ${file} (${bytes.length} bytes)`);
}
await writeFile(new URL('npc-voice-manifest.js',root),'// Generated by scripts/cache-npc-voice.mjs; text and audio must match exactly.\nexport const NPC_VOICE_CLIPS = Object.freeze('+JSON.stringify(Object.fromEntries(entries),null,2)+');\n');
console.log(`Completed ${entries.length} local story clips.`);
