import {readFile,writeFile} from 'node:fs/promises';
import {createFp1Story} from '../fp1-story.js';
import {createBailian} from '../server/bailian.mjs';

const root=new URL('../',import.meta.url);
const voices={
  '老朋友':createBailian({speechVoice:'Ethan'}),
  '阿晴':createBailian({speechVoice:'Kiki'}),
  '芳姐':createBailian({speechVoice:'Kiki'})
};
if (!voices['芳姐'].status().configured) throw Error('本地语音配置未启用');
const lines=new Map();
function collect(state) {
  if (state.text) lines.set(state.text,{speaker:state.speaker,id:state.route||state.phase});
}
for (const route of ['recover','borrow','buy']) {
  const story=createFp1Story();
  collect(story.snapshot());
  for (const action of ['start','defer','accept','arriveStreet','enter','arriveCounter','handTicket',route]) {
    if (!story.act(action)) throw Error('样段状态表有误');
    collect(story.snapshot());
  }
}
lines.set('她明天要面试，取错了外套。我们陪她去问问？',{speaker:'老朋友',id:'explain'});
const clips={};
const valid=bytes=>bytes?.length>44&&bytes.toString('ascii',0,4)==='RIFF'&&bytes.toString('ascii',8,12)==='WAVE';
let cached={};
try {
  const {FP1_CLIPS}=await import('../fp1-clips.js');
  cached=FP1_CLIPS;
} catch (error) {
  if (error.code!=='ERR_MODULE_NOT_FOUND') throw error;
}
for (const [text,{speaker,id}] of lines) {
  const file=`assets/fp1-line-${id}.wav`;
  const dest=new URL(file,root);
  let bytes;
  if (cached[text]===file) try {bytes=await readFile(dest);} catch {}
  if (!valid(bytes)) {
    const reply=await voices[speaker].speak({text});
    bytes=Buffer.from(reply.audioBase64,'base64');
    if (!valid(bytes)) throw Error(`无效的配音文件：${id}`);
    await writeFile(dest,bytes);
  }
  clips[text]=file;
  console.log(`${id} ${bytes.length} bytes`);
}
await writeFile(new URL('fp1-clips.js',root),'// Fixed sample lines generated by scripts/cache-fp1-voice.mjs.\nexport const FP1_CLIPS = Object.freeze('+JSON.stringify(clips,null,2)+');\n');
