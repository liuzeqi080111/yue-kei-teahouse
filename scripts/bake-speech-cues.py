"""Generate timing for the game's fixed recordings with Rhubarb's phonetic recognizer."""
import argparse
from concurrent.futures import ThreadPoolExecutor
import json
from pathlib import Path
import subprocess
import tempfile
import wave

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('rhubarb', help='Path to the Rhubarb Lip Sync executable')
options = parser.parse_args()
assets = root / 'assets'


def cues(path):
    # Some streaming TTS outputs leave placeholder lengths in the WAV header.
    with tempfile.TemporaryDirectory() as work:
        audio = Path(work) / 'line.wav'
        with wave.open(str(path), 'rb') as source, wave.open(str(audio), 'wb') as target:
            target.setparams(source.getparams())
            target.writeframes(source.readframes(source.getnframes()))
        result = subprocess.run(
            [options.rhubarb, '-r', 'phonetic', '-f', 'json', '--threads', '1', str(audio)],
            check=True, capture_output=True, text=True, encoding='utf-8',
        )
    timing = json.loads(result.stdout)['mouthCues']
    starts = [round(cue['start'] * 100) for cue in timing]
    starts.append(round(timing[-1]['end'] * 100))
    return path.name, [starts, ''.join(cue['value'] for cue in timing)]


recordings = sorted(p for p in assets.glob('*.wav') if p.name.startswith(('fp1-', 'npc-', 'street-', 'story-')))
with ThreadPoolExecutor(max_workers=6) as pool:
    data = dict(pool.map(cues, recordings))
manifest = root / 'npc-voice-manifest.js'
start = '// Generated by scripts/bake-speech-cues.py.\nexport const NPC_SPEECH_CUES = '
stop = '\n// End generated speech cues.\n'
source = manifest.read_text(encoding='utf-8')
before, found, section = source.partition(start)
tail = section.partition(stop)[2] if found else ''
# One recording per line keeps updates to individual recordings reviewable.
rows = ',\n'.join(' ' + json.dumps(name) + ':' + json.dumps(cues, separators=(',', ':')) for name, cues in data.items())
manifest.write_text(before.rstrip() + '\n\n' + start + '{\n' + rows + '\n};' + stop + tail, encoding='utf-8')
print(f'{len(data)} recordings')
